export type TextKey = keyof typeof words;
export function translate(language: Language, key: TextKey): string {
  return words[key]?.[{ ru: 0, kk: 1, en: 2 }[language]] ?? words[key]?.[2] ?? key;
}
export const I18nContext = createContext<{ lang: Language; setLang: (lang: Language) => void }>({ lang: 'ru', setLang: () => {} });
export function useI18n() {
  const context = useContext(I18nContext);
  return { ...context, t: (key: TextKey) => translate(context.lang, key) };
}
export function dateLabel(value: string | null | undefined, language: Language) {
  if (!value) return '—';
  const date = new Date(value.length === 10 ? value + 'T12:00:00' : value);
  return Number.isNaN(date.getTime()) ? value : new Intl.DateTimeFormat({ ru: 'ru-RU', kk: 'kk-KZ', en: 'en-GB' }[language], { day: 'numeric', month: 'short', year: 'numeric' }).format(date);
}
export const enumLabel = (value: string, language: Language) => value in words ? translate(language, value as TextKey) : value;
